import Foundation

enum SkillError: LocalizedError {
    case missingResources
    case existingSkill
    case generationFailed(Error)

    var errorDescription: String? {
        switch self {
        case .missingResources: return L10n.text("The bundled Skill template is missing.")
        case .existingSkill: return L10n.text("This folder contains another Skill or a symbolic link. Choose a different directory.")
        case .generationFailed(let error): return L10n.format("Could not generate Skill: %@", error.localizedDescription)
        }
    }
}

/// Installs a bundled code-control skill without accessing scripts or changing their configuration.
@MainActor
final class SkillManager {
    let isDevelopmentApp: Bool
    var skillName: String { isDevelopmentApp ? "scriptser-dev-control" : "scriptser-control" }
    var appName: String { isDevelopmentApp ? "Scriptser DEV" : "Scriptser" }
    private let templateURL: URL?
    private let fileManager = FileManager.default
    private static let marker = "<!-- Generated by Scriptser: code skill v2 -->"
    private static let legacyMarker = "<!-- Generated by Scriptser: UI skill v1 -->"

    static var defaultDirectory: String {
        let home = ProcessInfo.processInfo.environment["CODEX_HOME"]
        let root = home.flatMap { $0.isEmpty ? nil : $0 }
            ?? FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent(".codex").path
        return URL(fileURLWithPath: root).appendingPathComponent("skills").path
    }

    init(isDevelopmentApp: Bool = Bundle.main.bundleIdentifier == "com.scriptser.scr1.preview",
         templateURL: URL? = L10n.resourceBundle.url(forResource: "scriptser-control", withExtension: nil, subdirectory: "Skills")) {
        self.isDevelopmentApp = isDevelopmentApp
        self.templateURL = templateURL
    }

    func destination(in directory: String) -> URL {
        URL(fileURLWithPath: directory, isDirectory: true).appendingPathComponent(skillName, isDirectory: true)
    }

    func preview() throws -> String {
        guard let templateURL else { throw SkillError.missingResources }
        return try renderedFile(at: templateURL.appendingPathComponent("SKILL.md"))
    }

    func installationPrompt(in directory: String) -> String {
        L10n.format("Read the Skill at %@ and use it to operate %@ through its local code API. Only perform the actions I request.",
                    destination(in: directory).appendingPathComponent("SKILL.md").path, appName)
    }

    @discardableResult
    func generate(in directory: String) throws -> URL {
        guard let templateURL else { throw SkillError.missingResources }
        let parent = URL(fileURLWithPath: directory, isDirectory: true)
        let target = destination(in: directory)
        let stage = parent.appendingPathComponent(".\(skillName)-stage-\(UUID())")
        let backup = parent.appendingPathComponent(".\(skillName)-backup-\(UUID())")
        var backedUp = false
        do {
            let exists = fileManager.fileExists(atPath: target.path)
            // Never follow an existing skill's symlinks or overwrite someone else's package.
            for path in [target, target.appendingPathComponent("SKILL.md"),
                         target.appendingPathComponent("references"), target.appendingPathComponent("references/ui.md"),
                         target.appendingPathComponent("references/cli.md"), target.appendingPathComponent("scripts"),
                         target.appendingPathComponent("scripts/scriptserctl.py")] {
                if (try? fileManager.attributesOfItem(atPath: path.path)[.type] as? FileAttributeType) == .typeSymbolicLink {
                    throw SkillError.existingSkill
                }
            }
            if exists {
                let content = try? String(contentsOf: target.appendingPathComponent("SKILL.md"), encoding: .utf8)
                guard content?.contains(Self.marker) == true || content?.contains(Self.legacyMarker) == true else { throw SkillError.existingSkill }
            }
            // Render everything before mutating the destination; a missing template cannot leave a partial skill.
            let skill = try preview()
            let reference = try renderedFile(at: templateURL.appendingPathComponent("references/cli.md"))
            let client = try renderedFile(at: templateURL.appendingPathComponent("scripts/scriptserctl.py"))
            try fileManager.createDirectory(at: parent, withIntermediateDirectories: true)
            if exists { try fileManager.copyItem(at: target, to: stage) }
            else { try fileManager.createDirectory(at: stage, withIntermediateDirectories: false) }
            try fileManager.createDirectory(at: stage.appendingPathComponent("references"), withIntermediateDirectories: true)
            try skill.write(to: stage.appendingPathComponent("SKILL.md"), atomically: true, encoding: .utf8)
            try reference.write(to: stage.appendingPathComponent("references/cli.md"), atomically: true, encoding: .utf8)
            try fileManager.createDirectory(at: stage.appendingPathComponent("scripts"), withIntermediateDirectories: true)
            try client.write(to: stage.appendingPathComponent("scripts/scriptserctl.py"), atomically: true, encoding: .utf8)
            // Remove only the obsolete bundled guide; retain any user-maintained replacement.
            let legacy = stage.appendingPathComponent("references/ui.md")
            if let text = try? String(contentsOf: legacy, encoding: .utf8),
               text.hasPrefix("# Interface operations"), text.contains("## Manager and menu bar") {
                try fileManager.removeItem(at: legacy)
            }
            if exists {
                try fileManager.moveItem(at: target, to: backup)
                backedUp = true
            }
            try fileManager.moveItem(at: stage, to: target)
            if backedUp {
                do { try fileManager.removeItem(at: backup) }
                catch { AppLogger.settings.error("Could not remove Skill backup: \(error.localizedDescription)") }
            }
            AppLogger.settings.info("Generated Skill at \(target.path)")
            return target
        } catch {
            if backedUp {
                do { try fileManager.moveItem(at: backup, to: target) }
                catch { AppLogger.settings.error("Could not restore Skill backup at \(backup.path): \(error.localizedDescription)") }
            }
            try? fileManager.removeItem(at: stage)
            if let error = error as? SkillError { throw error }
            throw SkillError.generationFailed(error)
        }
    }

    private func renderedFile(at url: URL) throws -> String {
        let appURL = Bundle.main.bundleURL
        let target = appURL.pathExtension == "app" ? appURL.path : appName
        let targetJSON = String(decoding: try JSONEncoder().encode(target), as: UTF8.self)
        return try String(contentsOf: url, encoding: .utf8)
            .replacingOccurrences(of: "scriptser-control", with: skillName)
            .replacingOccurrences(of: "{{APP_NAME}}", with: appName)
            .replacingOccurrences(of: "{{SUPPORT_NAME}}", with: isDevelopmentApp ? "Scriptser-DEV" : "Scriptser")
            .replacingOccurrences(of: "{{APP_TARGET_JSON}}", with: targetJSON)
            .replacingOccurrences(of: "{{BUNDLE_ID}}", with: isDevelopmentApp ? "com.scriptser.scr1.preview" : "com.ingoo.scriptser")
    }
}
